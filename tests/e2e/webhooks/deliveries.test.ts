import {tokenCustody} from '../public-api/custody';
import { env } from 'cloudflare:test';
import { test, expect, vi } from 'vitest';
import { apiFixture } from '../public-api/support';
import { createOpaqueToken } from '../../../src/core/platform/auth/token';
import { createUlid } from '../../../src/core/shared/ulid';
import { scheduleWebhooks } from '../../../src/core/features/webhooks/worker';
import { sessionFor } from '../setup/fixtures';

test('owner webhook subscriptions sign current readable events, persist backoff, replay and disable once without following refused destinations', async () => {
  const f = await apiFixture(), credentialKey = createOpaqueToken();
  const bindings = { ...env, SLATE_PROFILE: undefined, CONNECTOR_CREDENTIALS_KEY: credentialKey };
  const request = async (path: string, method = 'GET', body?: unknown, member = f.owner) => {
    const response = await f.api.request('https://slate.test/api/developer/webhooks' + path, { method, headers: { cookie: f.cookies[member]!, 'content-type': 'application/json' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }, bindings);
    return { status: response.status, data: await response.json<any>() };
  };
  const ok = async (...args: Parameters<typeof request>) => { const result = await request(...args); expect(result.status, result.status >= 400 ? JSON.stringify(result.data) : '').toBe(200); return result.data; };
  const receiver: { body: string; headers: Headers; url: string }[] = [];
  let failure = false, redirect = false;
  const edge = vi.spyOn(globalThis, 'fetch').mockImplementation(async (input, init) => {
    const url = new URL(input instanceof Request ? input.url : String(input));
    if (url.hostname === 'cloudflare-dns.com') return Response.json({ Answer: url.searchParams.get('type') === 'A' ? [{ type: 1, data: '8.8.8.8' }] : [] });
    expect(url.hostname).toBe('synthetic-slate-1.example.com');
    expect(init?.redirect).toBe('manual');
    receiver.push({ body: String(init?.body), headers: new Headers(init?.headers), url: url.href });
    return new Response(redirect ? 'Redirect refused' : failure ? '<script>synthetic-slate-failure</script>' : 'synthetic-slate-received', { status: redirect ? 302 : failure ? 503 : 200, ...(redirect ? { headers: { location: 'http://127.0.0.1/private' } } : {}) });
  });
  try {
    const input = { operationKey: createUlid(), name: 'synthetic-slate-events', containerId: f.containerId, destination: 'https://synthetic-slate-1.example.com/events', events: ['page', 'record', 'comment', 'status', 'verification', 'member'] };
    for (const destination of ['http://synthetic-slate-1.example.com', 'https://127.0.0.1', 'https://10.0.0.1', 'https://[::1]', 'https://localhost', 'https://local.internal', 'https://example.invalid', 'https://user:pass@synthetic-slate-1.example.com', 'https://synthetic-slate-1.example.com:8443', 'https://synthetic-slate-1.example.com/#fragment']) expect((await request('', 'POST', { ...input, operationKey: createUlid(), destination })).status).toBe(400);
    expect(receiver).toHaveLength(0);
    expect((await request('', 'POST', input, f.member)).status).toBe(403);
    const created = await ok('', 'POST', input), id = created.value.id;
    expect(!!created.secret).toBe(true);
    const replayedGrant=await ok('','POST',input);expect(replayedGrant.value).toEqual(created.value);expect(replayedGrant).not.toHaveProperty('secret');
    expect((await ok('','GET',undefined,f.member)).items).toEqual([]);
    const list = await ok(''); expect(JSON.stringify(list).includes(created.secret)).toBe(false); expect(JSON.stringify(list).includes('credential_ciphertext')).toBe(false);
    const page = await f.ok('/api/pages', 'POST', { operationKey: createUlid(), containerId: f.containerId, title: 'synthetic-slate-readable' });
    const exchangesBeforeMissingKey=edge.mock.calls.length;
    await expect(scheduleWebhooks({...bindings,CONNECTOR_CREDENTIALS_KEY:undefined})).rejects.toMatchObject({code:'CREDENTIAL_UNAVAILABLE'});
    expect(edge.mock.calls.length).toBe(exchangesBeforeMissingKey);
    expect(receiver).toHaveLength(0);
    await Promise.all([scheduleWebhooks(bindings), scheduleWebhooks(bindings)]);
    expect(receiver).toHaveLength(1);
    const sent = receiver[0]!, [timestamp, signature] = sent.headers.get('slate-signature')!.split(',');
    const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(created.secret), { name: 'HMAC', hash: 'SHA-256' }, false, ['verify']);
    const bytes = Uint8Array.from(signature!.slice(3).match(/../g)!, hex => parseInt(hex, 16));
    expect(await crypto.subtle.verify('HMAC', key, bytes, new TextEncoder().encode(`${timestamp!.slice(2)}.${sent.body}`))).toBe(true);
    expect(JSON.parse(sent.body).target).toMatchObject({ id: page.value.pageId, title: 'synthetic-slate-readable' });
    const history = await ok(`/${id}/deliveries`), delivery = history.items[0];
    expect(delivery.state).toBe('sent'); expect(delivery.attempts).toHaveLength(1);
    await ok(`/${id}/deliveries/${delivery.id}/replay`, 'POST', { operationKey: createUlid() });
    await scheduleWebhooks(bindings);
    expect(receiver).toHaveLength(2);
    expect(receiver[1]!.headers.get('slate-event-id')).toBe(sent.headers.get('slate-event-id'));
    expect(receiver[1]!.headers.get('slate-signature')).not.toBe(sent.headers.get('slate-signature'));
    expect(JSON.parse(receiver[1]!.body).replay).toBe(true);
    // Change current access after an event was committed, before its clock delivery.
    await env.DB.prepare("UPDATE pages SET access_inheritance='restricted' WHERE id=?").bind(page.value.pageId).run();
    await ok(`/${id}/deliveries/${delivery.id}/replay`, 'POST', { operationKey: createUlid() });
    await scheduleWebhooks(bindings);
    expect(receiver).toHaveLength(2);
    expect((await ok(`/${id}/deliveries`)).items[0]).toMatchObject({ state: 'withheld' });
    await env.DB.prepare("UPDATE pages SET access_inheritance='inherit' WHERE id=?").bind(page.value.pageId).run();
    await f.ok(`/api/comments/page/${page.value.pageId}`,'POST',{operationKey:createUlid(),body:[{text:'synthetic-slate-comment'}]});
    await f.ok('/api/status','POST',{operationKey:createUlid(),key:'synthetic-slate-draft',label:'Synthetic draft',color:'#888888',requiresVerification:false});
    await f.ok('/api/status','POST',{operationKey:createUlid(),key:'synthetic-slate-verified',label:'Synthetic verified',color:'#338855',requiresVerification:true});
    let document=await f.ok(`/api/pages/${page.value.pageId}`);
    await f.ok(`/api/status/page/${page.value.pageId}`,'POST',{operationKey:createUlid(),expectedRevisionId:document.page.revisionId,statusKey:'synthetic-slate-draft'});
    document=await f.ok(`/api/pages/${page.value.pageId}`);
    await f.ok(`/api/pages/${page.value.pageId}/open`,'POST',{operationKey:createUlid(),revisionId:document.workingRevisionId});
    await f.ok(`/api/status/page/${page.value.pageId}`,'POST',{operationKey:createUlid(),expectedRevisionId:document.page.revisionId,statusKey:'synthetic-slate-verified',attestRevisionId:document.workingRevisionId});
    const database=await f.request('/api/databases','POST',{operationKey:createUlid(),containerId:f.containerId,title:'synthetic-slate-database'});
    expect(database.status).toBe(201);
    const record=await f.request(`/api/databases/${database.data.value.id}/records`,'POST',{operationKey:createUlid(),title:'synthetic-slate-record',values:{}});
    expect(record.status).toBe(201);
    await f.ok('/api/members/current/theme','PUT',{operationKey:createUlid(),theme:'dark'});
    await scheduleWebhooks(bindings);
    expect(new Set(receiver.map(item=>JSON.parse(item.body).type))).toEqual(new Set(input.events));
    failure = true;
    const failing = await f.ok('/api/pages', 'POST', { operationKey: createUlid(), containerId: f.containerId, title: 'synthetic-slate-retry' });
    const start = Date.now();
    for (const seconds of [0, 60, 300, 1800, 7200, 21600, 43200, 86400]) await scheduleWebhooks(bindings, new Date(start + seconds * 1000).toISOString());
    const failed = (await ok(`/${id}/deliveries`)).items.find((item: any) => item.attempts.some((attempt: any) => attempt.status === 503));
    expect(failed.state).toBe('failed'); expect(failed.attempts.length).toBeGreaterThan(1);
    expect((await ok('')).items[0].state).toBe('disabled');
    const notices = await env.DB.prepare("SELECT detail_json FROM notifications WHERE id LIKE ? AND recipient_member_id=?").bind(`webhook-disabled:${id}:%`, f.owner).all<{ detail_json: string }>();
    expect(notices.results).toHaveLength(1); expect(JSON.parse(notices.results[0]!.detail_json).outcome.includes('disabled')).toBe(true);
    await scheduleWebhooks(bindings, new Date(start + 86401000).toISOString());
    expect(await env.DB.prepare("SELECT count(*) AS n FROM notifications WHERE id LIKE ? AND recipient_member_id=?").bind(`webhook-disabled:${id}:%`, f.owner).first<number>('n')).toBe(1);
    vi.useFakeTimers({toFake:['Date']});vi.setSystemTime(start+86401000);
    const inbox=await f.ok('/api/notifications');
    expect(inbox.items.some((item:any)=>item.detail?.outcome?.includes('was disabled'))).toBe(true);
    vi.useRealTimers();
    failure = false;
    await ok(`/${id}/enable`, 'POST', { operationKey: createUlid() });
    await ok(`/${id}/deliveries/${failed.id}/replay`, 'POST', { operationKey: createUlid() });
    await scheduleWebhooks(bindings);
    expect((await ok(`/${id}/deliveries`)).items.find((item: any) => item.id === failed.id).state).toBe('sent');
    redirect = true;
    await f.ok('/api/pages', 'POST', { operationKey: createUlid(), containerId: f.containerId, title: 'synthetic-slate-redirect' });
    const before = receiver.length; await scheduleWebhooks(bindings);
    expect(receiver.length).toBe(before + 1);
    expect((await ok(`/${id}/deliveries`)).items[0].attempts[0].outcome).toBe('redirect-refused');
    await f.ok(`/api/members/${f.other}/role`,'PUT',{operationKey:createUlid(),expectedRole:'member',role:'owner'});
    f.cookies[f.other]=await sessionFor(f.other,{freshProof:true});
    await f.ok('/api/sharing','POST',{operationKey:createUlid(),targetKind:'container',targetId:f.containerId,principalKind:'member',principalId:f.other,level:'edit'});
    const erased=await ok('','POST',{...input,operationKey:createUlid(),name:'synthetic-slate-erase'},f.other);
    await f.ok('/api/pages','POST',{operationKey:createUlid(),containerId:f.containerId,title:'synthetic-slate-erase-log'});
    redirect=false;await scheduleWebhooks(bindings);
    expect((await ok(`/${erased.value.id}/deliveries`)).items.length).toBeGreaterThan(0);
    await f.ok('/api/members/remove','POST',{operationKey:createUlid(),memberId:f.other,erase:true});
    expect(await env.DB.prepare('SELECT count(*) AS n FROM webhook_subscriptions WHERE id=?').bind(erased.value.id).first<number>('n')).toBe(0);
    expect(await env.DB.prepare('SELECT count(*) AS n FROM webhook_deliveries WHERE subscription_id=?').bind(erased.value.id).first<number>('n')).toBe(0);
    await f.ok('/api/activity/settings','PUT',{operationKey:createUlid(),retentionDays:400});
    const archiveToken=await f.mint();await tokenCustody(f,archiveToken.secret,[created.secret]);
    await env.DB.prepare("UPDATE members SET role='member' WHERE id=?").bind(f.owner).run();
    expect((await env.DB.prepare('SELECT state FROM webhook_subscriptions WHERE id=?').bind(id).first<{ state: string }>())!.state).toBe('disabled');
    f.cookies[f.owner]=await sessionFor(f.owner,{freshProof:true});
    expect((await ok('')).items.map((item:any)=>item.id)).toEqual([id]);
    await ok(`/${id}/remove`,'POST',{operationKey:createUlid()});
    expect((await ok('')).items[0].state).toBe('removed');
    expect((await f.ok('/api/activity?action=webhook.remove')).items.some((item:any)=>item.action==='webhook.remove')).toBe(true);
  } finally { edge.mockRestore(); vi.useRealTimers(); }
});
