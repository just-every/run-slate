import {test,expect,vi,afterEach} from 'vitest';
import {trialFixture,waitUntil} from '../inquiry/trial-fixture';
import {executeTrial} from '../../../src/core/features/experiments/execution';
import {collectMeasurements} from '../../../src/core/features/experiments/measurement';
import {concludeTrial} from '../../../src/core/features/experiments/service';
import {prepareLearnedSkill} from '../../../src/core/features/experiments/learning';
import {requireSkillRevisionDisclosure} from '../../../src/core/features/skills/disclosure';
import {resolveEvidence} from '../../../src/core/features/ai/evidence';
import {chooseRoute} from '../../../src/core/features/ai/model-policy';
import {maximumCost} from '../../../src/core/features/ai/provider';
afterEach(()=>vi.unstubAllGlobals());
test('SKILL-002 full trial provenance reservation explains fixed100000 refusal and explicit finite150000 owner test ceiling',async()=>{
 const f=await trialFixture([1,20,1,20]);
 await waitUntil(f.plan.startsAt);await executeTrial(f.context(),f.trialId);await collectMeasurements(f.context(),f.trialId);await waitUntil(f.plan.endsAt);
 const concluded=await concludeTrial(f.context(),{id:f.trialId,operationKey:'measured-conclude',expectedRevisionId:f.active.value.revisionId,instrumentationRevision:f.plan.instrumentationRevision});
 const learned=await prepareLearnedSkill(f.context(),{id:f.trialId,operationKey:'measured-learned',expectedRevisionId:concluded.value.methodRevision});
 const definition=await requireSkillRevisionDisclosure(f.context(),learned.value.skillRevisionId);
 const packet=await resolveEvidence(f.context(),definition.refs,[f.owner],{current:true});
 const chosen=await chooseRoute(f.context(),f.ask.kind,f.ask.frontier);
 const required=maximumCost(chosen.route,f.ask.question+definition.instructions,packet,f.ask.maxOutputTokens);
 expect(definition.maxCostMicros).toBe(1);expect(required).toBeGreaterThan(100000);expect(required).toBeLessThan(150000);
 vi.unstubAllGlobals();
 console.log(JSON.stringify({id:'measured-learned-normal-reservation',requiredReservationMicros:required,originalCap:1,refusedSyntheticOwnerCap:100000,explicitSufficientOwnerCap:150000,route:chosen.route.model,outputTokens:f.ask.maxOutputTokens,limits:'Controlled protocol fixture; unchanged conservative all-attempt budget calculation; no inference or automatic cap adjustment.'}));
},60000);
