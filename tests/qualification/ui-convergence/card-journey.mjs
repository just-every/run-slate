import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {expect} from '@playwright/test';
import {accessible} from './browser-evidence.mjs';
import {openNavigation} from './browser-support.mjs';
export async function cardJourney(state){
 const {page,context,origin,api}=state;
 const response=await context.request.post(origin+'/api/containers',{data:{operationKey:randomUUID(),name:'Support knowledge',visibility:'private'}});
 assert.ok(response.ok(),await response.text());const space=(await response.json()).value;
 await page.goto(`${origin}/app/containers/${space.id}`,{waitUntil:'networkidle'});
 await page.getByRole('navigation',{name:'Space navigation',exact:true}).getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('checkbox',{name:'Use this space as a knowledge collection',exact:true}).check();
 await expect.poll(async()=>(await api(`/api/containers/${space.id}/collection`)).isCollection).toBe(true);
 await accessible(page,'knowledge collection settings');
 await openNavigation(page);
 await page.getByRole('button',{name:'Create',exact:true}).click();
 const menu=page.getByRole('menu',{name:'Create content',exact:true});
 await accessible(page,'create knowledge card menu');
 await menu.getByRole('menuitem',{name:'Knowledge card',exact:true}).click();
 await page.waitForURL(url=>url.pathname.startsWith('/app/pages/'));
 const id=new URL(page.url()).pathname.split('/').at(-1),title='How does CardJourney handover work?';
 await page.getByRole('textbox',{name:'Page title',exact:true}).fill(title);
 await page.getByRole('textbox',{name:'Page title',exact:true}).press('Tab');
 const text=Array.from({length:600},()=> 'handover').join(' ');
 await page.getByRole('textbox',{name:'Page body',exact:true}).fill(text);
 await expect(page.getByRole('region',{name:'Knowledge card',exact:true}).or(page.getByRole('complementary',{name:'Knowledge card',exact:true})).getByRole('status')).toContainText('Consider a page');
 await expect.poll(async()=>(await api(`/api/pages/${id}`)).blocks[0]?.content.text[0].text).toBe(text);
 const stored=await api(`/api/pages/${id}`);
 assert.equal(stored.page.pageKind,'card');assert.equal(stored.page.containerId,space.id);assert.equal(stored.card.overLimit,true);
 await accessible(page,'long knowledge card warning');
 await page.reload({waitUntil:'networkidle'});
 await expect(page.getByRole('status').filter({hasText:'Consider a page'})).toBeVisible();
 await page.goto(origin+'/app/search',{waitUntil:'networkidle'});
 await page.getByRole('searchbox',{name:'Search your workspace',exact:true}).fill('CardJourney');
 await page.getByRole('button',{name:'Search',exact:true}).click();
 const result=page.locator('.search-results > li[data-card]');
 await expect(result.getByRole('heading',{name:title,exact:true})).toBeVisible();
 await expect(result.locator('.trust-state')).toHaveText('Unverified');
 await accessible(page,'compact knowledge card search result');
}
