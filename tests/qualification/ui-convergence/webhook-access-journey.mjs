import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { expect } from '@playwright/test';
import { accessible } from './browser-evidence.mjs';
import { ok } from './two-people-support.mjs';
export async function webhookAccessJourney(state) {
  const { page, context, origin, api, fixtureSql, runScheduled, setWebhookFailure } = state;
  const space = (await api('/api/containers')).items.find(c => c.name === 'Handbook');
  const panel = page.getByRole('region', { name: 'Webhooks', exact: true });
  await expect(panel.getByText('No webhook destinations have been added.', { exact: true })).toBeVisible();
  await panel.getByLabel('Webhook name', { exact: true }).fill('Handbook delivery');
  await panel.getByLabel('Destination URL', { exact: true }).fill('https://synthetic-slate-1.example.com/events');
  await panel.getByLabel('Webhook space', { exact: true }).selectOption(space.id);
  await panel.getByRole('button', { name: 'Add webhook', exact: true }).click();
  await expect(panel.getByLabel('Signing secret', { exact: true })).toBeVisible();
  const secret = await panel.getByLabel('Signing secret', { exact: true }).inputValue();
  assert.ok(secret.length > 0);
  await panel.getByRole('button', { name: 'Copy signing secret', exact: true }).click();
  await expect.poll(async () => (await page.evaluate(() => navigator.clipboard.readText())) === secret).toBe(true);
  await panel.getByRole('button', { name: 'I saved the signing secret', exact: true }).click();
  await expect(panel.getByLabel('Signing secret', { exact: true })).toHaveCount(0);
  await accessible(page, 'webhook-access-created');
  await ok(context, origin, 'POST', '/api/pages', { operationKey: randomUUID(), containerId: space.id, title: 'Delivery handbook update' });
  await runScheduled();
  const subscription = (await api('/api/developer/webhooks')).items.find(item => item.name === 'Handbook delivery');
  await panel.getByRole('button', { name: 'View deliveries for Handbook delivery', exact: true }).click();
  const history = panel.getByRole('region', { name: 'Webhook deliveries', exact: true });
  await expect(history).toContainText('sent');
  await accessible(page, 'webhook-access-delivered');
  await setWebhookFailure(true);
  await ok(context, origin, 'POST', '/api/pages', { operationKey: randomUUID(), containerId: space.id, title: 'Delivery outage example' });
  await runScheduled();
  await history.getByRole('button', { name: 'Refresh deliveries', exact: true }).click();
  await expect(history).toContainText('receiver-failed');
  await expect(history.locator('script')).toHaveCount(0);
  await expect(history).toContainText('<script>synthetic-slate-response</script>');
  await accessible(page, 'webhook-access-retry');
  const retry = (await api(`/api/developer/webhooks/${subscription.id}/deliveries`)).items.find(item => item.state === 'pending');
  const old = new Date(Date.now() - 86401000).toISOString(), due = new Date(Date.now() - 1000).toISOString();
  await fixtureSql([`UPDATE webhook_deliveries SET first_attempt_at='${old}',next_attempt_at='${due}',cycle_attempts=7 WHERE id='${retry.id}'`]);
  await runScheduled();
  await page.reload({ waitUntil: 'networkidle' });
  await expect(panel.getByRole('article', { name: 'Webhook Handbook delivery', exact: true })).toContainText('State: disabled');
  await accessible(page, 'webhook-access-disabled');
  await setWebhookFailure(false);
  await panel.getByRole('button', { name: 'Re-enable Handbook delivery', exact: true }).click();
  await expect(panel.getByRole('article', { name: 'Webhook Handbook delivery', exact: true })).toContainText('State: enabled');
  await panel.getByRole('button', { name: 'View deliveries for Handbook delivery', exact: true }).click();
  const replayResponse = page.waitForResponse(response => response.request().method() === 'POST'
    && new URL(response.url()).pathname === `/api/developer/webhooks/${subscription.id}/deliveries/${retry.id}/replay`);
  await history.getByRole('button', { name: `Replay event ${retry.eventId}`, exact: true }).click();
  assert.equal((await replayResponse).status(), 200);
  await runScheduled();
  await history.getByRole('button', { name: 'Refresh deliveries', exact: true }).click();
  await expect(history).toContainText('Replayed');
  assert.equal((await api(`/api/developer/webhooks/${subscription.id}/deliveries`)).items.find(item => item.id === retry.id).state, 'sent');
  await accessible(page, 'webhook-access-replayed');
}
