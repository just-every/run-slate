import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { expect } from '@playwright/test';
import { root } from '../../e2e/runtime-harness.mjs';
import { accessible } from './browser-evidence.mjs';
import { ok } from './two-people-support.mjs';

/** NOTIF-003: owner token setup, actual comment events and production cron, Slack HTTP edge only. */
export async function chatJourney(state, width = state.page.viewportSize().width) {
  const { page, context, origin, atRest, setSlackFailure, readSlackMessages } = state;
  const runScheduled=async()=>{
    await atRest("UPDATE notification_outbox SET created_at=date('now')||'T00:00:00.000Z' WHERE processed_at IS NULL; UPDATE chat_deliveries SET created_at=date('now')||'T00:00:00.000Z' WHERE state='pending' AND message_id IS NULL AND substr(created_at,1,10)=date('now')");
    await state.runScheduled();
  };
  const api = (method, route, data) => ok(context, origin, method, route, data);
  const evidence = path.join(root, '.artifacts/ui-convergence/chat');
  await mkdir(evidence, { recursive: true });
  const shot = async label => {
    await accessible(page, `chat ${label}`);
    await page.screenshot({ path: path.join(evidence, `chat-${width}-${label}.png`), fullPage: true });
  };
  const open = async () => {
    await page.goto(`${origin}/app/settings?section=chat`, { waitUntil: 'networkidle' });
    await expect(page.getByRole('heading', { name: 'Send updates to chat.', exact: true })).toBeVisible();
  };
  const status = page.getByRole('region', { name: 'Slack delivery status: TTEST/GTEST', exact: true });
  const save = async () => {
    await page.getByLabel('Slack bot token', { exact: true }).fill('TEST-ONLY-SLACK-BOT-TOKEN');
    await page.getByRole('button', { name: 'Save chat delivery', exact: true }).click();
    await expect(status.getByRole('status')).toHaveText('Connected');
  };
  const space = (await api('GET', '/api/containers')).items.find(item => item.name === 'Handbook');
  const body = 'PRIVATE-CHAT-BODY-SENTINEL';
  const pageId = (await api('POST', '/api/pages', { operationKey: randomUUID(), containerId: space.id, title: 'Slack delivery runbook',
    blocks: [{ id: randomUUID(), blockType: 'paragraph', treePosition: 'a0', content: { text: [{ text: body }] } }] })).value.pageId;
  await api('POST', '/api/sharing', { operationKey: randomUUID(), targetKind: 'page', targetId: pageId, principalKind: 'member', principalId: 'browser-reader', level: 'view' });
  const comment = extra => api('POST', `/api/comments/page/${pageId}`, { operationKey: randomUUID(), body: [{ text: body }], ...extra });
  const history = async () => (await api('GET', '/api/notifications/chat/deliveries')).items;
  const count = async () => (await readSlackMessages()).length;

  await open();
  await expect(page.getByText('No chat delivery is connected.', { exact: true })).toBeVisible();
  await shot('not-connected');
  await page.getByLabel('Private channel ID', { exact: true }).fill('GTEST');
  await page.getByRole('checkbox', { name: 'comment', exact: true }).check();
  await page.getByRole('checkbox', { name: 'mention', exact: true }).check();
  await setSlackFailure('public_channel');
  await page.getByLabel('Slack bot token', { exact: true }).fill('TEST-ONLY-SLACK-BOT-TOKEN');
  await page.getByRole('button', { name: 'Save chat delivery', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText(/private Slack channel.*not shared/);
  assert.equal((await api('GET', '/api/notifications/chat')).connection, null);
  await expect(page.getByLabel('Private channel ID', { exact: true })).toHaveValue('GTEST');
  await shot('destination-refused');
  await setSlackFailure('ok');
  await save();
  await shot('connected');
  await setSlackFailure('public_channel');
  await comment(); await runScheduled();
  assert.equal(await count(), 0, 'A channel that becomes public is rechecked and nothing is sent.');
  await open(); await expect(status).toContainText('private_unshared_channel_required');
  await shot('channel-blocked');
  await setSlackFailure('ok');
  const first = await comment();
  await comment({ body: [{ text: 'Morgan Reader', mention: { kind: 'person', id: 'browser-reader', label: 'Morgan Reader' } }] });
  await runScheduled();
  await expect.poll(count).toBe(3);
  const sent = await readSlackMessages();
  assert.deepEqual(sent.map(item => item.text.split(' · ')[0]).sort(), ['comment', 'comment', 'mention']);
  for (const item of sent) {
    assert.equal(item.accepted, true);
    assert.ok(item.text.includes('Alex Owner') && item.text.includes('Slack delivery runbook') && item.text.includes(`/app/pages/${pageId}`));
    assert.equal(JSON.stringify(item).includes(body), false);
  }
  await comment({ threadId: first.value.threadId, parentCommentId: first.value.id });
  await runScheduled();
  assert.equal(await count(), 3, 'Unselected replies do not reach Slack.');
  await open();
  await expect(status).toContainText('Last delivered:');
  await shot('delivered');

  await setSlackFailure('rate_limited');
  await comment(); await runScheduled();
  assert.equal(await count(), 4);
  await open(); await expect(status).toContainText('rate_limited');
  await shot('transient-failure');
  await setSlackFailure('ok'); await runScheduled();
  assert.equal(await count(), 4, 'Retry waits for its scheduled time.');
  await atRest("UPDATE chat_deliveries SET next_attempt_at='2000-01-01T00:00:00.000Z' WHERE state='pending'");
  await atRest("UPDATE chat_connections SET retry_after=NULL");
  await runScheduled(); assert.equal(await count(), 5);
  assert.equal((await history()).filter(item => item.state === 'delivered').length, 4);
  await open(); await expect(status).toContainText('Last delivered:');
  await shot('retry-delivered');

  await setSlackFailure('channel_not_found');
  await comment(); await runScheduled();
  const permanentCount = await count();
  await setSlackFailure('ok'); await runScheduled();
  assert.equal(await count(), permanentCount, 'Permanent failure is not retried.');
  await open(); await expect(status).toContainText('channel_not_found');
  await shot('permanent-failure');
  await setSlackFailure('token_revoked');
  await comment(); await runScheduled();
  await open(); await expect(status.getByRole('status')).toHaveText('Needs attention');
  await shot('needs-attention');
  const retained = await history(), stoppedCount = await count();
  await comment(); await runScheduled();
  assert.equal(await count(), stoppedCount, 'Revoked authorization stops further sends.');
  await page.getByRole('button', { name: 'Reconnect', exact: true }).click();
  for (const name of ['comment', 'mention']) await expect(page.getByRole('checkbox', { name, exact: true })).toBeChecked();
  await expect(page.getByLabel('Slack bot token', { exact: true })).toHaveValue('');
  await shot('reconnect-form');
  await setSlackFailure('ok'); await save();
  assert.deepEqual(await history(), retained, 'Reconnect preserves delivery history.');
  await shot('reconnected');
  await page.getByRole('button', { name: 'Disconnect delivery', exact: true }).click();
  await expect(status.getByRole('status')).toHaveText('Disconnected');
  await shot('disconnected');
  await comment(); await runScheduled();
  assert.equal(await count(), stoppedCount, 'Disconnect stops all further messages.');
  // CHAT-001 extends this same panel and journey: destination lists and independent selections.
  const add = () => page.getByRole('button', { name: 'Add destination', exact: true }).click();
  await add();
  await page.getByLabel('Private channel ID', { exact: true }).fill('GSLATE2');
  await page.getByLabel('Slack bot token', { exact: true }).fill('synthetic-slate-101');
  await page.getByLabel('Events from', { exact: true }).selectOption(space.id);
  await page.getByRole('checkbox', {name:'comment',exact:true}).check();
  await page.getByRole('button',{name:'Save chat delivery',exact:true}).click();
  const second = page.getByRole('region',{name:'Slack delivery status: TTEST/GSLATE2',exact:true});
  await expect(second.getByRole('status')).toHaveText('Connected');
  await add();
  await page.getByLabel('Provider',{exact:true}).selectOption('teams');
  await page.getByLabel('Teams team/channel IDs',{exact:true}).fill('synthetic-slate-5/synthetic-slate-6');
  await page.getByLabel('Microsoft Graph access token',{exact:true}).fill('synthetic-slate-102');
  await page.getByRole('checkbox',{name:'published',exact:true}).check();
  await page.getByRole('button',{name:'Save chat delivery',exact:true}).click();
  const teams = page.getByRole('region',{name:'Teams delivery status: synthetic-slate-5/synthetic-slate-6',exact:true});
  await expect(teams.getByRole('status')).toHaveText('Connected');
  await shot('multiple-destinations');
  const publish=async()=>{const document=await api('GET',`/api/pages/${pageId}`);await api('POST',`/api/pages/${pageId}/publish`,{operationKey:randomUUID(),expectedRevisionId:document.page.revisionId});};
  const slackBefore=await count();
  await comment();await runScheduled();
  assert.equal(await count(),slackBefore+1);assert.equal((await state.readTeamsMessages()).length,0);
  await publish();await runScheduled();
  assert.equal(await count(),slackBefore+1);assert.equal((await state.readTeamsMessages()).length,1);
  for(const message of await state.readTeamsMessages()){
    assert.equal(message.body.contentType,'text');assert.equal(message.body.content.includes(body),false);
    assert.ok(message.body.content.includes(`/app/pages/${pageId}`));assert.ok(message.key);
  }
  await open();await expect(second).toContainText('Last delivered:');await expect(teams).toContainText('Last delivered:');
  await shot('independent-selections');
  await state.setTeamsFailure('token_revoked');await publish();await runScheduled();
  const beforeOther=await count();await comment();await runScheduled();assert.equal(await count(),beforeOther+1);
  await open();await expect(teams.getByRole('status')).toHaveText('Needs attention');await expect(second.getByRole('status')).toHaveText('Connected');
  await shot('isolated-authorization-failure');
  await teams.getByRole('button',{name:'Reconnect',exact:true}).click();
  await expect(page.getByRole('checkbox',{name:'published',exact:true})).toBeChecked();
  await expect(page.getByLabel('Microsoft Graph access token',{exact:true})).toHaveValue('');
  await shot('teams-reconnect');
  await state.setTeamsFailure('ok');
  await page.getByLabel('Microsoft Graph access token',{exact:true}).fill('synthetic-slate-102');
  await page.getByRole('button',{name:'Save chat delivery',exact:true}).click();
  await expect(teams.getByRole('status')).toHaveText('Connected');
  await second.getByRole('button',{name:'Disconnect delivery',exact:true}).click();
  await expect(second.getByRole('status')).toHaveText('Disconnected');
  const stoppedSlack=await count(),teamsBefore=(await state.readTeamsMessages()).length;
  await comment();await publish();await runScheduled();assert.equal(await count(),stoppedSlack);assert.equal((await state.readTeamsMessages()).length,teamsBefore+1);
  await open();await shot('independent-disconnect');
  await teams.getByRole('button',{name:'Disconnect delivery',exact:true}).click();
  await expect(teams.getByRole('status')).toHaveText('Disconnected');
  await teams.getByRole('button',{name:'Reconnect',exact:true}).click();
  await page.getByLabel('Delivery schedule',{exact:true}).selectOption('daily');
  await page.getByLabel('Microsoft Graph access token',{exact:true}).fill('synthetic-slate-102');
  await page.getByRole('button',{name:'Save chat delivery',exact:true}).click();
  await open();await expect(teams).toContainText('Daily digest');
  const digestBefore=(await state.readTeamsMessages()).length;
  await publish();await runScheduled();assert.equal((await state.readTeamsMessages()).length,digestBefore);
  await atRest("UPDATE chat_deliveries SET created_at='2000-01-01T00:00:00.000Z' WHERE state='pending'");
  await runScheduled();assert.equal((await state.readTeamsMessages()).length,digestBefore+1);
  await open();await shot('daily-digest');
  await teams.getByRole('button',{name:'Edit delivery',exact:true}).click();
  await expect(page.getByLabel('Delivery schedule',{exact:true})).toHaveValue('daily');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await teams.getByRole('button',{name:'Disconnect delivery',exact:true}).click();
  await shot('all-disconnected');
  await add();await page.getByLabel('Provider',{exact:true}).selectOption('nook');
  await page.getByLabel('Nook channel ID',{exact:true}).fill('synthetic-slate-channel');
  await page.getByLabel('Nook channel token',{exact:true}).fill('synthetic-slate-103');
  await page.getByLabel('Delivery schedule',{exact:true}).selectOption('daily');
  await page.getByRole('button',{name:'Save chat delivery',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('no Nook notification service');
  await shot('nook-unavailable');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();

}
