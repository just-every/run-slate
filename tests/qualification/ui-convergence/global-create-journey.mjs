import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { expect } from '@playwright/test';
import { root } from '../../e2e/runtime-harness.mjs';
import { openNavigation } from './browser-support.mjs';
import { accessible } from './browser-evidence.mjs';
import { ok } from './two-people-support.mjs';

export async function globalCreateJourney(state) {
  const { page, context, origin, api } = state;
  const width = page.viewportSize().width;
  const shot = label => page.screenshot({ path: path.join(root, `.artifacts/ui-convergence/global-create-${width}-${label}.png`), fullPage: true });
  const space = (await api('/api/containers')).items.find(item => item.name === 'Handbook');
  const source = (await api('/api/pages')).items.find(item => item.title === 'Welcome');
  await ok(context, origin, 'POST', '/api/templates', { operationKey: randomUUID(), sourcePageId: source.id, includeChildren: false, containerId: null, title: 'Incident review', description: 'Capture what happened and follow up.', category: 'Operations' });
  const destinations = (await api('/api/navigation')).configuration.destinations.filter(item => item.visible);
  for (const destination of destinations) {
    await page.goto(origin + destination.href, { waitUntil: 'networkidle' });
    await openNavigation(page);
    await page.getByRole('button', { name: 'Create', exact: true }).click();
    const menu = page.getByRole('menu', { name: 'Create content' });
    for (const name of ['Page', 'Database', 'Space', 'Page from template']) await expect(menu.getByRole('menuitem', { name, exact: true })).toBeVisible();
    await page.keyboard.press('Escape');
  }
  await page.goto(origin + `/app/containers/${space.id}`, { waitUntil: 'networkidle' });
  await openNavigation(page);
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  const menu = page.getByRole('menu', { name: 'Create content' });
  await expect(menu.getByRole('menuitem', { name: 'Page', exact: true })).toHaveAccessibleDescription('in Handbook');
  await shot('menu');
  await menu.getByRole('menuitem', { name: 'Page', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Page title', exact: true })).toHaveValue('Untitled');
  const pageId = new URL(page.url()).pathname.split('/').at(-1);
  assert.equal((await api(`/api/pages/${pageId}`)).page.containerId, space.id);
  await page.getByRole('textbox', { name: 'Page title', exact: true }).fill('Incident response notes');
  await page.getByRole('textbox', { name: 'Page title', exact: true }).press('Tab');
  await expect.poll(async () => (await api(`/api/pages/${pageId}`)).page.title).toBe('Incident response notes');
  await shot('page');
  await openNavigation(page);
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Database', exact: true }).click();
  const database = page.getByRole('dialog', { name: 'Create a database', exact: true });
  await database.getByLabel('Name', { exact: true }).fill('Service ownership');
  await database.getByLabel('Space', { exact: true }).selectOption(space.id);
  await accessible(page, 'global create database destination');
  await shot('database');
  await database.getByRole('button', { name: 'Create database', exact: true }).click();
  await expect(page).toHaveURL(/\/app\/databases\/[^/]+$/);
  await expect(page.getByRole('heading', { name: 'Service ownership', exact: true })).toBeVisible();
  await shot('database-created');
  await openNavigation(page);
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Page from template', exact: true }).click();
  await page.locator('.template-choice').filter({ has: page.getByRole('heading', { name: 'Incident review', exact: true }) }).click();
  await page.getByRole('button', { name: 'Use this template', exact: true }).click();
  const template = page.getByRole('dialog', { name: 'Use this template', exact: true });
  await template.getByRole('combobox', { name: /^Create in/ }).selectOption({ label: 'Handbook' });
  await accessible(page, 'global create template destination');
  await shot('template');
  await template.getByRole('button', { name: 'Create page', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Page title', exact: true })).toBeVisible();
  const copyId = new URL(page.url()).pathname.split('/').at(-1);
  assert.notEqual(copyId, source.id);
  assert.equal((await api(`/api/pages/${copyId}`)).page.containerId, space.id);
  await shot('template-created');
  await openNavigation(page);
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Space', exact: true }).click();
  const container = page.getByRole('dialog', { name: 'Create a space', exact: true });
  await container.getByLabel('Name', { exact: true }).fill('Customer success');
  await container.getByLabel('Description', { exact: true }).fill('Shared customer support playbooks');
  await accessible(page, 'global create space');
  await shot('space');
  await container.getByRole('button', { name: 'Create space', exact: true }).click();
  await expect.poll(async () => (await api('/api/containers')).items.some(item => item.name === 'Customer success')).toBe(true);
  await shot('space-created');
  await state.switchIdentity('reader');
  await page.goto(origin + '/app', { waitUntil: 'networkidle' });
  await openNavigation(page);
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Database', exact: true }).click();
  await expect(database.getByLabel('Space', { exact: true })).toBeVisible();
  await expect(database.locator(`option[value="${space.id}"]`)).toHaveCount(0);
  await shot('reader-destinations');
  await database.getByRole('button', { name: 'Cancel', exact: true }).click();
}
