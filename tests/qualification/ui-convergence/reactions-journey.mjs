import { commentJourney } from './comments-journey.mjs';
import { commentAnchorsJourney } from './comment-anchors.mjs';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { expect } from '@playwright/test';
import { openPageAction } from './browser-support.mjs';
import { grant, ok, restrictedPage } from './two-people-support.mjs';

export async function reactionsJourney(state, people) {
  const { page, context, origin, api } = state;
  const width = page.viewportSize().width;
  const { pageId } = await restrictedPage(state, 'Customer incident handover', ['The on-call lead owns escalation decisions.']);
  await grant(context, origin, pageId, 'browser-reader', 'view');
  await commentJourney(state, pageId);
  const anchoredThread = (await api(`/api/comments/page/${pageId}`)).threads.find(thread => thread.kind === 'inline');
  await commentAnchorsJourney(state, pageId, anchoredThread);
  const comment = (await ok(context, origin, 'POST', `/api/comments/page/${pageId}`, { operationKey: randomUUID(), body: [{ text: 'Recovery confirmed; the next shift can take over.' }] })).value.id;
  await page.goto(`${origin}/app/pages/${pageId}`, { waitUntil: 'networkidle' });
  const section = page.getByRole('region', { name: 'Page reactions', exact: true });
  await page.locator('.page-reactions > summary').click();
  await section.getByRole('button', { name: 'React with thumbs up' }).click();
  await expect(section.getByRole('list', { name: 'Reactions', exact: true })).toContainText('👍 Alex Owner');
  await people.bob.page.goto(`${origin}/app/pages/${pageId}`, { waitUntil: 'networkidle' });
  await people.bob.page.locator('.page-reactions > summary').click();
  const readerSection = people.bob.page.getByRole('region', { name: 'Page reactions', exact: true });
  await expect(readerSection.getByRole('list')).toContainText('Alex Owner');
  const before = await api(`/api/analytics?pageId=${pageId}`);
  const inbox = await api('/api/notifications');
  await readerSection.getByRole('combobox', { name: 'Reaction emoji' }).selectOption('🎉');
  await readerSection.getByRole('button', { name: 'React with 🎉' }).click();
  await expect(readerSection.getByRole('list')).toContainText('🎉 Morgan Reader');
  await readerSection.screenshot({ path: `.artifacts/ui-convergence/reactions-${width}-page.png` });
  assert.deepEqual(await api(`/api/analytics?pageId=${pageId}`), before, 'A page reaction never records a view.');
  await openPageAction(people.bob.page, 'Comments');
  await people.bob.page.waitForLoadState('networkidle');
  const commentViews = await api(`/api/analytics?pageId=${pageId}`);
  const article = people.bob.page.locator(`#comment-${comment}`);
  await article.getByRole('button', { name: 'React with thumbs up' }).click();
  await expect(article.getByRole('list', { name: 'Reactions', exact: true })).toContainText('👍 Morgan Reader');
  await article.screenshot({ path: `.artifacts/ui-convergence/reactions-${width}-comment.png` });
  await people.shot('bob', 'comment reaction shows reader');
  const emojiControl = article.getByRole('combobox', { name: 'Reaction emoji' });
  await emojiControl.focus();
  await expect.poll(() => emojiControl.evaluate(element => getComputedStyle(element.closest('[data-tooltip]'), '::after').opacity)).toBe('1');
  await people.shot('bob', 'comment reaction emoji tooltip');
  await emojiControl.blur();
  await article.getByRole('button', { name: 'React with thumbs up' }).click();
  await expect(article.getByRole('list', { name: 'Reactions', exact: true })).toBeEmpty();
  assert.deepEqual(await api(`/api/analytics?pageId=${pageId}`), commentViews, 'Comment reaction add/remove never records a view.');
  await people.bob.page.locator('.detail-close').click();
  await people.bob.page.waitForLoadState('networkidle');
  const removalViews = await api(`/api/analytics?pageId=${pageId}`);
  await readerSection.getByRole('button', { name: 'React with 🎉' }).click();
  await expect(readerSection.getByRole('list')).not.toContainText('Morgan Reader');
  assert.deepEqual(await api(`/api/analytics?pageId=${pageId}`), removalViews, 'Removing a page reaction never records a view.');
  assert.deepEqual(await api('/api/notifications'), inbox, 'Reactions never notify the author.');
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('.page-reactions > summary').click();
  await expect(section.getByRole('list')).toContainText('Alex Owner');
  await expect(section.getByRole('list')).not.toContainText('Morgan Reader');
  await section.getByRole('button', { name: 'React with thumbs up' }).click();
  await expect(section.getByRole('list')).toBeEmpty();
  await section.screenshot({ path: `.artifacts/ui-convergence/reactions-${width}-removed.png` });
}
