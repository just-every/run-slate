import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {expect} from '@playwright/test';
import {signInWithOutbox} from '../../e2e/outbox-auth.mjs';
import {accessible} from './browser-evidence.mjs';
export async function shareMessageJourney(state){
 const {page,context,origin,api,atRest,switchIdentity,readerCookie}=state;
 const now=new Date().toISOString();
 await atRest(`INSERT INTO members(id,workspace_id,email,display_name,initials,role,member_kind,status,is_setup_owner,created_at,updated_at) VALUES('browser-teammate','browser-workspace','teammate@test.invalid','Casey Teammate','CT','member','member','active',0,'${now}','${now}');`);
 const teammate=await signInWithOutbox(origin,'teammate@test.invalid');
 const post=async(path,data)=>{const response=await context.request.post(origin+path,{data:{operationKey:randomUUID(),...data}});assert.ok(response.ok(),await response.text());return(await response.json()).value;};
 const space=await post('/api/containers',{name:'Support handovers',visibility:'private'});
 const doc=await post('/api/pages',{containerId:space.id,title:'Weekend support handover'});
 await post('/api/sharing',{targetKind:'page',targetId:doc.pageId,principalKind:'member',principalId:'browser-teammate',level:'view'});
 await page.goto(`${origin}/app/pages/${doc.pageId}`,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Share',exact:true}).click();
 const panel=page.getByRole('region',{name:'Share with a message',exact:true});
 await panel.getByRole('listbox',{name:'Message recipients',exact:true}).selectOption(['member:browser-teammate','member:browser-reader']);
 await panel.getByRole('textbox',{name:'Recipient email addresses',exact:true}).fill('partner@example.test');
 const message='Please review the weekend handover.\nBring the checklist <b>as text</b>.';
 await panel.getByRole('textbox',{name:'Message (optional)',exact:true}).fill(message);
 await panel.getByRole('button',{name:'Send page with message',exact:true}).click();
 await expect(panel).toContainText('Morgan Reader needs access. Nothing has been sent.');
 await expect(panel).toContainText('partner@example.test needs a guest invitation.');
 const notices=async cookie=>(await api('/api/notifications',{headers:{cookie}})).items.filter(n=>n.event==='page-shared');
 assert.equal((await notices(teammate.cookie)).length,1);
 assert.equal((await notices(readerCookie)).length,0);
 await accessible(page,'share message with explicit grant and guest invitation offers');
 await panel.getByRole('button',{name:'Add view access and send to Morgan Reader',exact:true}).click();
 await expect(panel.getByRole('button',{name:'Sent to Morgan Reader',exact:true})).toBeDisabled();
 assert.equal((await notices(readerCookie)).length,1);
 await accessible(page,'share message grant confirmed');
 await context.addCookies([{name:'slate_session',value:teammate.cookie.split('=')[1],url:origin}]);
 await page.goto(origin+'/app/inbox',{waitUntil:'networkidle'});
 await expect(page.locator('.outcome-list').filter({hasText:'page shared'})).toContainText(message);
 await expect(page.locator('.outcome-list')).toContainText('From Alex Owner');
 assert.equal(await page.locator('.outcome-list b').count(),0,'Message markup is plain text.');
 await accessible(page,'readable recipient gets one share message');
 await switchIdentity('reader');
 await page.goto(origin+'/app/inbox',{waitUntil:'networkidle'});
 await expect(page.locator('.outcome-list')).toContainText(message);
 await expect(page.locator('.outcome-list > li').filter({hasText:'page shared'})).toHaveCount(1);
 await accessible(page,'newly granted recipient gets one share message');
 await switchIdentity('owner');
 await page.goto(origin+'/app/settings?section=activity',{waitUntil:'networkidle'});
 await expect(page.getByRole('heading',{name:'What changed.',exact:true})).toBeVisible();
 await expect(page.locator('.settings-list')).toContainText(message);
 await accessible(page,'sender activity retains share message');
}
