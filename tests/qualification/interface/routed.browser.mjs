import {portabilityChecks} from './portability.mjs';
import {socialChecks} from './social.mjs';
import {blockChecks} from './blocks.mjs';
import {treeChecks} from './tree.mjs';
import {templateChecks} from './templates.mjs';
import {editingChecks} from './editing.mjs';
import {publicationChecks} from './publication.mjs';
import {resourceChecks} from './resource.mjs';
import {linkChecks} from './links.mjs';
import {decisionChecks} from './decisions.mjs';
import {visualChecks} from './visuals.mjs';
import {pageChecks} from './pages.mjs';
import {inquiryChecks} from './inquiry.mjs';
import {shellChecks} from './shell.mjs';
import {structuredChecks} from './structured.mjs';
import {saveChecks} from './saving.mjs';
import {policyChecks} from './policies.mjs';
import {contentChecks} from './content.mjs';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {setTimeout as delay} from 'node:timers/promises';
import {chromium} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {createRuntime} from '../local/runtime.mjs';
import {fixtureFirstOwner} from '../local/first-owner.mjs';
const evidence=process.env.QUAL_EVIDENCE??new URL('../../../.artifacts/interface/',import.meta.url).pathname;
const selected=process.env.QUAL_MODULES?.split(',');const enabled=name=>!selected||selected.includes(name);
const checks=[];let runtime,browser,page;
const check=(clauses,name)=>checks.push({clauses,name,passed:true});
try{
 runtime=await createRuntime({root:process.cwd(),evidence,appPort:8742,inspectorPort:8743});
 browser=await chromium.launch({headless:true});const context=await browser.newContext({viewport:{width:1440,height:1000}});
 // Pace the real browser traffic below the ordinary 600/minute operator limit.
 let nextRequest=0;await context.route('**/api/**',async route=>{const at=Math.max(Date.now(),nextRequest);nextRequest=at+150;await delay(at-Date.now());await route.continue();});
 ({page}=await fixtureFirstOwner(runtime,context));check(['WORK-013'],'Real wizard creates exactly one workspace, first container and first page');
 await page.goto(runtime.origin+'/app');await page.getByRole('heading',{name:'Recent pages',exact:true}).waitFor();check(['NAV-001'],'Home displays recents, favourites and membership spaces');
 const response=await context.request.get(runtime.origin+'/api/pages');const {items}=await response.json();const id=items[0].id;
 await page.goto(runtime.origin+'/app/pages/'+id);
 const title=page.getByRole('textbox',{name:'Page title',exact:true});await title.fill('Interface qualification page');await title.press('Tab');await page.getByRole('status').filter({hasText:/^Saved$/}).waitFor();
 await page.reload();await title.waitFor();assert.equal(await title.inputValue(),'Interface qualification page');check(['SAVE-001','PAGE-001'],'Title shows Saved after commit and survives reload');
 const editable=page.locator('[data-slate-editable]').first();await editable.fill('Labelled interface fixture text');await page.getByRole('status').filter({hasText:/^Saved /}).first().waitFor();await page.reload();await page.getByRole('textbox',{name:'Paragraph'}).waitFor();
 check(['SAVE-001','BLOCK-001'],'Body text commits on the real routed editor and survives reload');
 await page.getByRole('textbox',{name:'Paragraph'}).press('/');await page.getByPlaceholder('Type to search').waitFor();check(['BLOCK-003'],'Typing slash opens the actual insert menu');await page.keyboard.press('Escape');
 for(const width of [320,390,430,1440]){await page.setViewportSize({width,height:900});await page.screenshot({path:`${runtime.directory}/page-${width}.png`,fullPage:true});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`horizontal overflow at ${width}`);}
 check(['NAV-006'],'Page renders without horizontal overflow at 320,390,430 and 1440 pixels');
 const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();await writeFile(runtime.directory+'/axe.json',JSON.stringify(axe,null,2));assert.deepEqual(axe.violations.map(v=>({id:v.id,nodes:v.nodes.length})),[]);
 check(['BASE-UI-001'],'Routed page axe automated checks; no blanket WCAG acceptance');
 if(enabled('portability'))await portabilityChecks({page,context,runtime,id,check});
 if(enabled('content'))await contentChecks({page,context,runtime,id,check});
 if(enabled('saving'))await saveChecks({page,context,runtime,id,check});
 if(enabled('shell'))await shellChecks({page,context,runtime,id,browser,check});
 if(enabled('inquiry'))await inquiryChecks({page,context,runtime,id,check});
 if(enabled('decisions'))await decisionChecks({page,context,runtime,id,check});
 if(enabled('links'))await linkChecks({page,context,runtime,id,browser,check});
 if(enabled('resource'))await resourceChecks({page,context,runtime,id,check});
 if(enabled('social'))await socialChecks({page,context,runtime,id,browser,check});
 if(enabled('blocks'))await blockChecks({page,context,runtime,id,browser,check});
 if(enabled('tree'))await treeChecks({page,context,runtime,id,browser,check});
 if(enabled('editing'))await editingChecks({page,context,runtime,id,browser,check});
 if(enabled('pages')||enabled('templates'))await pageChecks({page,context,runtime,id,check});
 if(enabled('templates'))await templateChecks({page,context,runtime,id,check});
 const structured=enabled('structured')||enabled('policies')||enabled('visuals')?await structuredChecks({page,context,runtime,id,check}):{};
 if(enabled('policies'))await policyChecks({page,context,runtime,id,check,...structured});
 if(enabled('publication'))await publicationChecks({page,context,runtime,id,browser,check});
 if(enabled('visuals'))await visualChecks({page,runtime,id,check,...structured});
 await writeFile(runtime.directory+'/routed.json',JSON.stringify({selectedModules:selected??'all',checks,artifact:runtime.artifact,limits:'Local emitted Worker with labelled identity/content fixtures; no inference, email or external provider proof.'},null,2));console.log(runtime.directory);
}catch(error){if(runtime){await writeFile(runtime.directory+'/failure.html',await page?.content()??'');await page?.screenshot({path:runtime.directory+'/failure.png',fullPage:true}).catch(()=>{});await writeFile(runtime.directory+'/failure.json',JSON.stringify({checks,error:error.stack},null,2));console.error(runtime.directory);}throw error;}finally{await browser?.close();await runtime?.close();}
