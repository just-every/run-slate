test("STAT-001 STAT-002 STAT-003 STAT-004 STAT-005: exact-open verification, stale/lapsed semantics and vocabulary persistence across both status profiles", async () => {
    for (const status of ['verification-only', 'open-vocabulary'] as const) {
        await resetDeployment();
        const { owner, containerId } = await scenario();
        await env.DB.batch(defaultStatusStatements(env.DB, owner.actor.workspaceId, owner.now));
        await profile(owner, { 'page.status.v1': status });
        expect((await rows('SELECT label FROM status_entries WHERE workspace_id=?', owner.actor.workspaceId)).map(r => r.label).sort()).toEqual(['In progress', 'Ready for review', 'Rough draft', 'Verified']);
        await setStatusEntry(owner, { operationKey: key('custom'), key: 'bespoke', label: 'Bespoke', color: '#112233', requiresVerification: false });
        const p = await createPage(owner, { operationKey: key('page'), containerId, title: 'Attested' }), id = p.value.pageId;
        const input = { operationKey: key('attest'), expectedRevisionId: p.receipt.revisionId, statusKey: 'verified', attestRevisionId: p.receipt.revisionId, expiresAt: new Date(Date.parse(owner.now) + 1000).toISOString() };
        await expect(setPageStatus(owner, id, input)).rejects.toMatchObject({ code: 'REVISION_NOT_OPENED' });
        await openPage(owner, id, { operationKey: key('open'), revisionId: p.receipt.revisionId });
        const verified = await setPageStatus(owner, id, input);
        expect(await verification(owner, id)).toMatchObject({ revision_id: p.receipt.revisionId, owner_member_id: owner.actor.id, current: true, lapsed: false });
        const before = await rows('SELECT * FROM page_verifications WHERE page_id=?', id);
        await profile(owner, { 'page.status.v1': status === 'verification-only' ? 'open-vocabulary' : 'verification-only' });
        expect(await rows('SELECT * FROM page_verifications WHERE page_id=?', id)).toEqual(before);
        expect((await readPage(owner, id)).properties.statusKey).toBe('verified');
        await updatePage(owner, id, { operationKey: key('edit'), expectedRevisionId: verified.receipt.revisionId, properties: { title: 'Changed after attestation' } });
        expect(await verification(owner, id)).toMatchObject({ current: false, lapsed: false });
        const later = new Date(Date.parse(owner.now) + 2000).toISOString();
        await runContentJobs(env, later);
        await dispatchCommittedNotifications({ ...owner, now: later });
        await runContentJobs(env, later);
        await dispatchCommittedNotifications({ ...owner, now: later });
        expect(await verification({ ...owner, now: later }, id)).toMatchObject({ current: false, lapsed: true });
        expect(await rows('SELECT revision_id,expires_at FROM page_verifications WHERE page_id=?', id)).toEqual(before.map(r => ({ revision_id: r.revision_id, expires_at: r.expires_at })));
        const notices = await rows("SELECT * FROM notifications WHERE source_page_id=? AND event='verification-lapsed'", id);
        expect(notices).toHaveLength(1);
        await setStatusEntry(owner, { operationKey: key('retire'), key: 'verified', label: 'Verified', color: '#228855', requiresVerification: true, retire: true });
        expect((await readPage(owner, id)).properties.statusKey).toBe('verified');
    }
});
test('ARCH-001 ARCH-002 ARCH-003 ARCH-004 ARCH-005 ARCH-006 LIFE-007 REV-005 LINK-002: archive/trash/restore preserves descendants and history, confirmed erase removes content and R2', async () => {
    const { owner, containerId } = await scenario();
    const p = await createPage(owner, { operationKey: key('root'), containerId, title: 'Root secret', blocks: [textBlock(key('block'), 'Erasure secret')] }), id = p.value.pageId;
    const child = await createPage(owner, { operationKey: key('child'), containerId, parentPageId: id, title: 'Child secret' });
    await createComment(owner, id, { operationKey: key('comment'), body: [{ text: 'Comment secret' }] });
    const file = await uploadMedia(owner, { operationKey: key('file'), pageId: id, name: 'secret.txt', contentType: 'text/plain', bytes: new TextEncoder().encode('Secret R2 bytes') });
    const fileRows = await rows('SELECT storage_key FROM files WHERE id=?', file.value.id);
    const history = await revisionHistory(owner, id), comments = await listComments(owner, id), before = await readPage(owner, id);
    await archivePage(owner, id, { operationKey: key('archive'), expectedRevisionId: before.page.revisionId, action: 'archive', reason: 'Completed' });
    expect((await readPage(owner, id)).permissions.canEdit).toBe(false);
    expect((await readPage(owner, child.value.pageId)).page.lifecycle).toBe('archived');
    expect((await listPages(owner, containerId)).items.map(r => r.id)).not.toContain(id);
    expect(await revisionHistory(owner, id)).toEqual(history);
    expect(await listComments(owner, id)).toEqual(comments);
    await expect(updatePage(owner, id, { operationKey: key('archived-edit'), expectedRevisionId: before.page.revisionId, properties: { title: 'Disallowed' } })).rejects.toMatchObject({ code: 'PAGE_READ_ONLY' });
    await archivePage(owner, id, { operationKey: key('restore'), expectedRevisionId: before.page.revisionId, action: 'restore' });
    expect((await readPage(owner, id)).workingRevisionId).toBe(before.workingRevisionId);
    expect((await readPage(owner, child.value.pageId)).parentPageId).toBe(id);
    await archivePage(owner, id, { operationKey: key('trash'), expectedRevisionId: before.page.revisionId, action: 'trash' });
    await expect(readPage(owner, id)).rejects.toMatchObject({ status: 404 });
    await expect(permanentDeletePage(owner, id, { operationKey: key('incomplete'), confirmedPageIds: [id] })).rejects.toMatchObject({ code: 'CONFIRM_CASCADE' });
    await permanentDeletePage(owner, id, { operationKey: key('erase'), confirmedPageIds: [id, child.value.pageId] });
    expect(await rows('SELECT * FROM page_blocks WHERE page_id=?', id)).toEqual([]);
    for (const r of await rows('SELECT * FROM page_revisions WHERE page_id=?', id))
        expect(r).toMatchObject({ body_json: '[]', properties_json: '{}', content_hash: '', author_member_id: null, deleted_at: owner.now });
    expect(await rows('SELECT anchor_json,block_id FROM comment_threads WHERE page_id=?', id)).toEqual([{ anchor_json: null, block_id: null }]);
    expect(await rows('SELECT original_name,size_bytes,deleted_at FROM files WHERE page_id=?', id)).toEqual([{ original_name: 'Deleted file', size_bytes: 0, deleted_at: owner.now }]);
    await runContentJobs(env, owner.now);
    expect(await owner.files.get(fileRows[0].storage_key as string)).toBeNull();
    await expect(readRevision(owner, id, p.receipt.revisionId)).rejects.toMatchObject({ status: 404 });
});
test('LIFE-007 ARCH-005: discarding private draft trashes it, retains original revision, and emits no other member notification/tree trace', async () => {
    const { owner, reader, containerId } = await scenario();
    const { notificationList } = await import('../../../src/core/features/notifications/service');
    const p = await createPage(owner, { operationKey: key('draft'), containerId, title: 'Discard me privately', lifecycle: 'draft' });
    expect((await listPages(owner, containerId)).items.map(p => p.id)).toContain(p.value.pageId);
    await archivePage(owner, p.value.pageId, { operationKey: key('discard'), expectedRevisionId: p.receipt.revisionId, action: 'trash' });
    expect((await listPages(reader)).items).toEqual([]);
    expect((await notificationList(reader)).items).toEqual([]);
    expect(await rows('SELECT id,deleted_at FROM page_revisions WHERE page_id=?', p.value.pageId)).toEqual([{ id: p.receipt.revisionId, deleted_at: null }]);
    expect((await rows('SELECT trashed_at,deleted_at FROM pages WHERE id=?', p.value.pageId))[0]).toEqual({ trashed_at: owner.now, deleted_at: null });
    await archivePage(owner, p.value.pageId, { operationKey: key('restore'), expectedRevisionId: p.receipt.revisionId, action: 'restore' });
    expect((await readPage(owner, p.value.pageId)).page.lifecycle).toBe('draft');
});
