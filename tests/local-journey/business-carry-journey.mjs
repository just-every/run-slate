import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { parseEnv } from 'node:util';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { userInfo } from 'node:os';
import { createBusinessCarryRuntime, exampleBusinessCarry } from './business-carry-runtime.mjs';
import { captureBusinessCarry } from './business-carry-capture.mjs';
import { createBusinessCarryRestart } from './business-carry-restart.mjs';
import { setTimeout as delay } from 'node:timers/promises';

const root = fileURLToPath(new URL('../../', import.meta.url));
const evidence = join(root, '.artifacts/business-carry');
assert.equal(process.env.HOME, userInfo().homedir, 'the browser driver uses the real HOME');
console.log('Public proof head ' + execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim());
const require = createRequire(join(root, 'package.json'));
const { chromium, expect: baseExpect } = require('@playwright/test');
const expect = baseExpect.configure({ timeout: 30_000 });
const original = exampleBusinessCarry;
const { carryFile, start, run, until, stop } = await createBusinessCarryRuntime(root, evidence);
let dev, browser, captureFailure;
const timeline = [], network = [];
try {
  await run('reset', ['--yes']);
  await run('setup', ['--owner-email', 'you@example.test', '--port', '49761']);
  await rm(carryFile, { force: true });
  const vars = parseEnv(await readFile(join(root, '.dev.vars'), 'utf8'));
  const origin = vars.APP_URL;
  dev = start('dev', ['--foreground']);
  await until(async () => { try { return (await fetch(origin + '/health')).status === 200 && dev.output.includes('RER_READY'); } catch { return false; } }, 'real rer dev did not become ready');
  const key = parseEnv(await readFile(join(root, '.rer/local/dev-key.env'), 'utf8')).RER_DEV_KEY;
  assert.match(chromium.executablePath(), /chromium-12(?:4[3-9]|[5-9]\d)/);
  browser = await chromium.launch({ headless: true, args: ['--use-mock-keychain', '--password-store=basic'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  assert.equal((await context.request.post(origin + '/__dev/key', { data: { key } })).status(), 204);
  const page = await context.newPage();
  const networkStarted = Date.now();
  page.on('response', response => network.push({ ms: Date.now() - networkStarted, path: new URL(response.url()).pathname, status: response.status(), type: response.request().resourceType() }));
  page.on('requestfailed', request => network.push({ ms: Date.now() - networkStarted, path: new URL(request.url()).pathname, failed: request.failure()?.errorText }));
  page.on('pageerror', error => network.push({ ms: Date.now() - networkStarted, error: error.message.split('\n')[0].replace(/[?#][^ ]+/g, '') }));
  const slowRestarts = [];
  await page.goto(origin + '/auth/dev/enter?as=owner');
  await page.waitForURL(origin + '/setup');
  const name = () => page.getByLabel('Workspace name', { exact: true });
  await expect(name()).toBeEnabled();
  const capture = (label, target = page) => captureBusinessCarry(evidence, label, target);
  captureFailure = () => capture('failed-public-step');
  const changeCarry = createBusinessCarryRestart({ page, context, origin, carryFile, evidence, timeline, slowRestarts });
  await expect(name()).toHaveValue('');
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled();
  await capture('01-no-business');
  assert.equal(await page.evaluate(() => JSON.parse(sessionStorage.getItem('slate-first-run-draft')).workspaceName), '');
  await changeCarry(original);
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeEnabled();
  await capture('02-business-prefill');
  const setupHtml = await (await context.request.get(origin + '/setup')).text();
  assert.ok(!setupHtml.includes(original.business_id), 'only the Business name crosses into setup');
  assert.equal((await fetch(origin + '/api/workspace')).status, 401, 'Business carry grants no session or authority');
  for (const path of ['/api/workspace', '/api/workspace/first-run', '/api/navigation', '/api/session']) {
    const response = await context.request.get(origin + path);
    assert.equal(response.status(), 200);
    const serialized = JSON.stringify(await response.json());
    assert.ok(!serialized.includes('"business":') && !serialized.includes(original.business_id), `${path} excludes carry data`);
  }
  assert.equal(await page.evaluate(() => JSON.parse(sessionStorage.getItem('slate-first-run-draft')).workspaceName), '');
  const editPage = await context.newPage();
  await editPage.goto(origin + '/setup');
  const editedName = editPage.getByLabel('Workspace name', { exact: true });
  for (const size of [161, 200]) {
    await editedName.fill('a'.repeat(size));
    await expect(editPage.getByRole('button', { name: 'Continue', exact: true })).toBeEnabled();
  }
  await capture('13-name-200', editPage);
  await editedName.fill('a'.repeat(201));
  await expect(editPage.getByRole('alert')).toContainText('characters');
  await expect(editPage.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled();
  await capture('14-name-201-refused', editPage);
  await editedName.fill('Studio notes');
  await expect(editPage.getByLabel('Workspace name', { exact: true })).toHaveValue('Studio notes');
  await editPage.reload();
  await expect(editPage.getByLabel('Workspace name', { exact: true })).toHaveValue('Studio notes');
  await capture('02b-owner-edited', editPage);
  await editPage.close();
  console.log('Carried field accepts edits and retains a typed answer across reload.');
  await changeCarry(null);
  await expect(name()).toHaveValue('');
  await capture('03-file-removed-same-tab');
  await changeCarry(original);
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Space name', { exact: true }).fill('Team handbook');
  await page.getByLabel('First page title', { exact: true }).fill('Welcome');
  await capture('04-first-space');
  await page.reload();
  await expect(page.getByLabel('Space name', { exact: true })).toHaveValue('Team handbook');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await capture('05-invitations');
  await page.getByRole('button', { name: 'Skip this step', exact: true }).click();
  await page.waitForURL(/\/app\/pages\//);
  const savedPagePath = new URL(page.url()).pathname;
  await expect(page.getByRole('textbox', { name: 'Page title', exact: true })).toHaveValue('Welcome');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await expect(page.getByTestId('workspace-name')).toContainText(original.name);
  await capture('06-carried-workspace-ready');
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    for (const label of width === 1440 ? ['Comments', 'History', 'Details'] : ['Comments']) {
      const control = page.getByRole('button', { name: label, exact: true });
      const tooltip = await control.getAttribute('data-tooltip');
      assert.ok(tooltip.split(' ').length >= 2 && tooltip.split(' ').length <= 4);
      await control.hover();
      await delay(350);
      await page.screenshot({ path: join(evidence, 'shots', `tooltip-${label.toLowerCase()}-${width}.png`) });
    }
  }
  for (const path of ['/api/workspace', '/api/workspace/first-run', '/api/navigation', '/api/session']) {
    const response = await context.request.get(origin + path);
    assert.equal(response.status(), 200);
    const serialized = JSON.stringify(await response.json());
    assert.ok(!serialized.includes('"business":') && !serialized.includes(original.business_id), `${path} keeps carry metadata private`);
  }
  await changeCarry({ ...original, name: 'Renamed Business Co' });
  assert.equal((await (await context.request.get(origin + '/api/workspace')).json()).name, original.name);
  const savedDocument = await context.request.get(origin + savedPagePath.replace('/app/', '/api/'));
  console.log(`Saved page API after carry restart: ${savedDocument.status()}`);
  assert.equal(savedDocument.status(), 200);
  assert.equal((await savedDocument.json()).page.title, 'Welcome');
  await expect(page.getByRole('textbox', { name: 'Page title', exact: true })).toHaveValue('Welcome');
  await capture('07-saved-name-after-business-change');
  await changeCarry(null);
  assert.equal((await (await context.request.get(origin + '/api/workspace')).json()).name, original.name);
  assert.equal(new URL(page.url()).pathname, savedPagePath);
  await capture('08-saved-name-after-file-removal');
  await changeCarry({ ...original, name: 'Later Business Co' });
  assert.equal((await (await context.request.get(origin + '/api/workspace')).json()).name, original.name);
  await capture('09-file-appears-after-completion');
  await page.goto(origin + '/setup');
  await page.waitForURL(/\/app/);
  console.log('Finished setup remains finished; saved workspace, page and session survive carry restarts.');
  const carryLog = dev.output.split('\n').filter(line => line.includes('No Business carry') || line.includes('server restarted'));
  await writeFile(join(evidence, 'dev-carry.log'), carryLog.join('\n') + '\n');
  await context.close();
  await stop();
  console.log('Starting a fresh no-Business fixture after proving saved data survives carry restarts.');
  await run('reset', ['--yes']);
  await run('setup', ['--owner-email', 'you@example.test', '--port', '49761']);
  await rm(carryFile, { force: true });
  dev = start('dev', ['--foreground']);
  await until(async () => { try { return (await fetch(origin + '/health')).status === 200 && dev.output.includes('RER_READY'); } catch { return false; } }, 'fresh no-Business dev did not become ready');
  const freshKey = parseEnv(await readFile(join(root, '.rer/local/dev-key.env'), 'utf8')).RER_DEV_KEY;
  const fresh = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  assert.equal((await fresh.request.post(origin + '/__dev/key', { data: { key: freshKey } })).status(), 204);
  const unpaired = await fresh.newPage();
  await unpaired.goto(origin + '/auth/dev/enter?as=owner');
  await unpaired.waitForURL(origin + '/setup');
  await expect(unpaired.getByLabel('Workspace name', { exact: true })).toHaveValue('');
  await capture('10-no-business-fresh', unpaired);
  await unpaired.getByLabel('Workspace name', { exact: true }).fill('Studio notes');
  await capture('11-no-business-owner-types', unpaired);
  await unpaired.getByRole('button', { name: 'Continue', exact: true }).click();
  await unpaired.getByLabel('Space name', { exact: true }).fill('Team handbook');
  await unpaired.getByLabel('First page title', { exact: true }).fill('Welcome');
  await unpaired.getByRole('button', { name: 'Continue', exact: true }).click();
  await unpaired.getByRole('button', { name: 'Skip this step', exact: true }).click();
  await unpaired.waitForURL(/\/app\/pages\//);
  await unpaired.setViewportSize({ width: 1440, height: 1000 });
  await expect(unpaired.getByTestId('workspace-name')).toHaveText('Studio notes');
  await capture('12-no-business-workspace-ready', unpaired);
  await fresh.close();
  assert.deepEqual(slowRestarts, [], 'Every restart must restore the document and APIs within ten seconds');
  console.log('No Business: an empty field accepts the owner name and completes with that saved name.');
} catch (error) {
  await captureFailure?.();
  console.error(`${error.name}: ${String(error.message).split('\n')[0]}`);
  process.exitCode = 1;
} finally {
  await writeFile(join(evidence, 'text', 'restart-timelines.json'), JSON.stringify(timeline, null, 2) + '\n');
  await writeFile(join(evidence, 'text', 'network.json'), JSON.stringify(network, null, 2) + '\n');
  if (dev) await writeFile(join(evidence, 'dev-carry-last.log'), dev.output.split('\n').filter(line => /server restarted\.|No Business carry/.test(line)).join('\n') + '\n');
  await browser?.close();
  await stop();
}
